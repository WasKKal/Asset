function Lucide.GetAsset(iconName, iconSize)
    if type(iconName) ~= "string" then
        error("Lucide.GetAsset: Argument 1 (iconName): expected type string", 2)
    end
    local name = string.match(string.lower(iconName), "^%s*(.*)%s*$") or iconName
    local data = IconData[name]
    if not data then
        error("Lucide.GetAsset: Failed to find icon: " .. name, 2)
    end
    local sheetAsset = getSheetAsset(data[1])
    if not sheetAsset then return nil end
    return {
        IconName = name,
        Url = sheetAsset,
        ImageRectSize = Vector2.new(ICON_SIZE, ICON_SIZE),
        ImageRectOffset = Vector2.new(data[2], data[3]),
    }
end

function Lucide.ImageLabel(iconName, iconSize, props)
    iconSize = iconSize or 256
    local asset = Lucide.GetAsset(iconName, iconSize)
    if not asset then return nil end
    local label = Instance.new("ImageLabel")
    label.Name = asset.IconName
    label.Size = UDim2.fromOffset(iconSize, iconSize)
    label.BackgroundColor3 = Color3.new(0, 0, 0)
    label.BackgroundTransparency = 1
    label.BorderSizePixel = 0
    label.Image = asset.Url
    label.ImageRectSize = asset.ImageRectSize
    label.ImageRectOffset = asset.ImageRectOffset
    label.ImageColor3 = Color3.new(1, 1, 1)
    label.ScaleType = Enum.ScaleType.Fit
    if props then
        for k, v in pairs(props) do
            if k ~= "Parent" then label[k] = v end
        end
        if props.Parent then label.Parent = props.Parent end
    end
    return label
end

